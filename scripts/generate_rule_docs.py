"""Generate ``docs/rules.md`` from the rule catalog.

Iterates ``load_default_catalog`` and writes one ``##`` section per rule
code carrying the title, severity, rationale and fix keys.  The catalog
is only read, never modified.  Run from the repository root::

    PYTHONPATH=src python scripts/generate_rule_docs.py
"""

from __future__ import annotations

from pathlib import Path
from sys import argv
from typing import TYPE_CHECKING, Final, final

from astart.rules.catalog import load_default_catalog
from astart.rules.facts import default_registries

if TYPE_CHECKING:
    from astart.rules.model import Catalog, Rule


@final
class Constants:
    """Constants for the rule docs generator.

    Attributes:
        root: Repository root directory.
        output: Where the generated ``docs/rules.md`` is written.
        header: Title block prepended to the generated document.

    """

    root: Final[Path] = Path(__file__).resolve().parent.parent
    output: Final[Path] = root / "docs" / "rules.md"
    header: Final[str] = """# Rules

One section per catalog rule, generated by
``scripts/generate_rule_docs.py``. Do not edit by hand; regenerate after
changing ``src/astart/rules/catalog/``.
"""


def _section(*, rule: Rule) -> str:
    """Render one rule as a markdown section.

    Args:
        rule: Catalog rule to document.

    Returns:
        Markdown text headed by the rule code.

    """
    fixes: str = (
        ", ".join(f"`{key}`" for key in rule.fixes) if rule.fixes else "none"
    )
    return (
        f"## {rule.code} — {rule.title}\n\n"
        f"- **Key:** `{rule.key}`\n"
        f"- **Severity:** {rule.severity.value}\n"
        f"- **Fixes:** {fixes}\n\n"
        f"{rule.rationale}\n"
    )


def render(*, catalog: Catalog) -> str:
    """Render the whole catalog as markdown.

    Args:
        catalog: Loaded rule catalog.

    Returns:
        The document text, rules sorted by code.

    """
    sections: list[str] = [
        _section(rule=rule)
        for rule in sorted(catalog.rules, key=lambda item: item.code)
    ]
    return Constants.header + "\n" + "\n".join(sections)


def main() -> int:
    """Write ``docs/rules.md`` and return the exit status.

    Returns:
        ``0`` on success.

    """
    output: Path = Path(argv[1]) if len(argv) > 1 else Constants.output
    catalog: Catalog = load_default_catalog(registries=default_registries())
    output.write_text(data=render(catalog=catalog), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
